// Language normalization: returns 'en', 'te', or 'ta'
export const getNormalizedLanguage = (lng) => {
  if (!lng) return 'en';
  const code = lng.split('-')[0].toLowerCase();
  return ['en', 'te', 'ta'].includes(code) ? code : 'en';
};

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'en',
    supportedLngs: ['en', 'te', 'ta'],
    load: 'languageOnly',
    cleanCode: true,
    interpolation: {
      escapeValue: false,
    },
    detection: {
      order: ['localStorage', 'navigator'],
      lookupLocalStorage: 'i18nextLng',
      caches: ['localStorage'],
    },
  });

// Synchronize document.documentElement.lang on language switch
i18n.on('languageChanged', (lng) => {
  const norm = getNormalizedLanguage(lng);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = norm;
  }
  try {
    localStorage.setItem('i18nextLng', norm);
  } catch (_) {}
});

export default i18n;
